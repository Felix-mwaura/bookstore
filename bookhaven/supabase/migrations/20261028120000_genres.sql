-- ─────────────────────────────────────────────────────────────
-- Genres become data, not a constant in the bundle.
--
-- Until now the shelf taxonomy lived in app/lib/categories.js, which meant
-- adding a genre was a code change and a deploy. This table is the source of
-- truth; the JS list survives only as the fallback the storefront renders
-- when the table cannot be read (a paused project, a network failure, a
-- first deploy before this migration runs). A storefront that has never
-- heard of a genre degrades to the old list; it does not go blank.
--
-- Books still name their genre in `books.category` (text). That is not
-- changed here: rewriting the column to a foreign key would reject every
-- book whose category was typed by hand before today. Instead the delete
-- guard below refuses to remove a genre that any book still names, which is
-- the invariant that actually matters — no book is ever left orphaned.
--
-- Idempotent: safe to run more than once.
-- ─────────────────────────────────────────────────────────────

create table if not exists public.genres (
  id         bigint generated by default as identity primary key,
  name       text not null,
  slug       text not null,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id) on delete set null
);

-- One row per name, ignoring case and stray spaces: "Self-Help", "self-help "
-- and "Self-Help" are the same genre, and the admin cannot create the third.
create unique index if not exists genres_name_key on public.genres (lower(btrim(name)));
create unique index if not exists genres_slug_key on public.genres (slug);

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'genres_name_length'
  ) then
    alter table public.genres
      add constraint genres_name_length check (char_length(btrim(name)) between 1 and 40);
  end if;
end $$;

-- The eight genres the shop launched with.
insert into public.genres (name, slug)
values
  ('Self-Help',    'self-help'),
  ('Finance',      'finance'),
  ('Productivity', 'productivity'),
  ('Psychology',   'psychology'),
  ('History',      'history'),
  ('Philosophy',   'philosophy'),
  ('Fiction',      'fiction'),
  ('Biography',    'biography')
on conflict do nothing;

-- Anything already in use on the shelf but missing above, so the admin sees
-- every genre a book actually has and the delete guard cannot be tripped by a
-- category nobody can look up. Same slug rule as app/lib/categories.js:
-- lowercase, whitespace runs become single hyphens.
insert into public.genres (name, slug)
select distinct
       btrim(b.category),
       lower(regexp_replace(btrim(b.category), '\s+', '-', 'g'))
from public.books b
where b.category is not null
  and btrim(b.category) <> ''
on conflict do nothing;

-- ── the delete guard ────────────────────────────────────────
--
-- Enforced in the database, not only in the route that calls it, because the
-- service role is not the only door into the table and a count-then-delete in
-- application code is a race: a book can be assigned to the genre between the
-- two statements. Raising here means the delete either happens with no books
-- pointing at the genre, or does not happen at all.
create or replace function public.genres_refuse_delete_when_used()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  used integer;
begin
  select count(*) into used
  from public.books
  where btrim(lower(category)) = btrim(lower(old.name));

  if used > 0 then
    raise exception
      'This genre still has % book%s. Move them to another genre first.',
      used, case when used = 1 then '' else 's' end
      using errcode = 'foreign_key_violation';
  end if;

  return old;
end;
$$;

drop trigger if exists genres_refuse_delete_when_used on public.genres;
create trigger genres_refuse_delete_when_used
  before delete on public.genres
  for each row execute function public.genres_refuse_delete_when_used();

-- ── access ──────────────────────────────────────────────────
--
-- Read: everyone, because the storefront lists genres to anonymous visitors.
-- Write: nobody in the browser. The admin API uses the service role, which
-- bypasses RLS, and there is deliberately no insert/update/delete policy — a
-- forged request with the anon key can read the list and nothing else.
alter table public.genres enable row level security;

drop policy if exists "genres are readable by everyone" on public.genres;
create policy "genres are readable by everyone"
  on public.genres for select
  to anon, authenticated
  using (true);

revoke all on public.genres from anon, authenticated;
grant select on public.genres to anon, authenticated;
grant all on public.genres to service_role;
grant usage, select on sequence public.genres_id_seq to service_role;
