// Runs supabase/migrations/20261025120000_cod_abuse_limits.sql against a real
// Postgres (PGlite, PG 17) and attacks the trigger it installs.
//
// The point is not the happy path — it is that the DATABASE refuses the
// orders /api/orders refuses. A JavaScript check is advisory; two tabs, a
// script or a retried request can pass it twice.
//
//   node scripts/cod-sql-test.mjs

import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

let PGlite;
try {
  ({ PGlite } = await import("@electric-sql/pglite"));
} catch {
  console.log("SKIP — COD (SQL): @electric-sql/pglite is not installed.");
  console.log("       npm install --no-save @electric-sql/pglite && node scripts/cod-sql-test.mjs");
  process.exit(0);
}

const here = dirname(fileURLToPath(import.meta.url));
const migration = await readFile(
  join(here, "..", "supabase", "migrations", "20261025120000_cod_abuse_limits.sql"),
  "utf8"
);

const db = new PGlite();

let passed = 0;
let failed = 0;

function ok(label, condition, detail = "") {
  if (condition) {
    passed++;
    console.log(`  ok    ${label}`);
  } else {
    failed++;
    console.log(`  FAIL  ${label}${detail ? ` — ${detail}` : ""}`);
  }
}

async function sql(text, params) {
  return db.query(text, params);
}

// Supabase-shaped scaffold: a customer, the tables place_order() writes, and
// the actor identity the trigger reads.
await db.exec(`
  create schema if not exists auth;
  create role anon;
  create role authenticated;
  create role service_role;

  create table public.books (
    id bigint generated by default as identity primary key,
    title text,
    stock_quantity integer not null default 100
  );

  create table public.orders (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null,
    items jsonb not null default '[]'::jsonb,
    status text not null default 'Pending',
    payment_status text not null default 'pending',
    payment_method text,
    total integer not null default 0,
    created_at timestamptz not null default now()
  );

  grant all on all tables in schema public to anon, authenticated;
`);

await db.exec(migration);

console.log("\nCOD limits, enforced by the database\n");

const USER = "11111111-1111-1111-1111-111111111111";

async function insertOrder({ units = 1, method = "cod", payStatus = "pending", status = "Pending", user = USER, receipt = null } = {}) {
  const items = JSON.stringify([{ id: 1, quantity: units }]);
  return sql(
    `insert into public.orders (user_id, items, status, payment_status, payment_method, total)
     values ($1, $2::jsonb, $3, $4, $5, 100) returning id`,
    [user, items, status, payStatus, method]
  );
}

async function expectError(label, promise, code) {
  try {
    await promise;
    ok(label, false, "it was accepted");
  } catch (error) {
    const message = String(error.message || error);
    ok(label, message.includes(code), message.slice(0, 120));
  }
}

// ── one order ─────────────────────────────────────────────────────────────
await expectError("a 21-book COD order is refused", insertOrder({ units: 21 }), "COD_ORDER_TOO_LARGE");
ok("a 20-book COD order is accepted", (await insertOrder({ units: 20 })).rows.length === 1);

// ── open orders ───────────────────────────────────────────────────────────
const second = await insertOrder({ units: 1 });
const third = await insertOrder({ units: 1 });
ok("three open COD orders are allowed", second.rows.length === 1 && third.rows.length === 1);
await expectError("a fourth open COD order is refused", insertOrder({ units: 1 }), "TOO_MANY_OPEN_COD_ORDERS");

// …but only for the same customer
const other = await insertOrder({ units: 1, user: "22222222-2222-2222-2222-222222222222" });
ok("a different customer is unaffected", other.rows.length === 1);

// ── what does NOT count as an open hold ───────────────────────────────────
const userB = "33333333-3333-3333-3333-333333333333";
for (let i = 0; i < 3; i++) await insertOrder({ units: 1, user: userB, status: "Cancelled" });
ok(
  "cancelled COD orders do not count against the limit",
  (await insertOrder({ units: 1, user: userB })).rows.length === 1
);

const userC = "44444444-4444-4444-4444-444444444444";
for (let i = 0; i < 3; i++) await insertOrder({ units: 1, user: userC, payStatus: "paid" });
ok(
  "paid COD orders do not count against the limit",
  (await insertOrder({ units: 1, user: userC })).rows.length === 1
);

const userD = "55555555-5555-5555-5555-555555555555";
for (let i = 0; i < 5; i++) await insertOrder({ units: 25, user: userD, method: "mpesa", payStatus: "paid" });
ok("M-Pesa orders are never limited (the money is already collected)", true);

// ── the "legacy" spellings the app still has to tolerate ──────────────────
const userE = "66666666-6666-6666-6666-666666666666";
for (let i = 0; i < 3; i++) await insertOrder({ units: 1, user: userE, method: "Cash on Delivery" });
await expectError(
  "a legacy 'Cash on Delivery' row still counts as a hold",
  insertOrder({ units: 1, user: userE }),
  "TOO_MANY_OPEN_COD_ORDERS"
);

const userF = "77777777-7777-7777-7777-777777777777";
for (let i = 0; i < 3; i++) await insertOrder({ units: 1, user: userF, method: "cod", payStatus: "pending", status: "Delivered" });
ok(
  "delivered orders are not a hold",
  (await insertOrder({ units: 1, user: userF })).rows.length === 1
);

// ── malformed items must not crash the trigger ────────────────────────────
const userG = "88888888-8888-8888-8888-888888888888";
let emptyOk = false;
try {
  await sql(
    `insert into public.orders (user_id, items, payment_method, payment_status, status, total)
     values ($1, '[]'::jsonb, 'cod', 'pending', 'Pending', 0)`,
    [userG]
  );
  emptyOk = true;
} catch {
  emptyOk = false;
}
ok("an empty item list passes the trigger (place_order rejects it separately)", emptyOk);

let badItemsOk = false;
try {
  await sql(
    `insert into public.orders (user_id, items, payment_method, payment_status, status, total)
     values ($1, '[{"quantity":"lots"}]'::jsonb, 'cod', 'pending', 'Pending', 0)`,
    [userG]
  );
  badItemsOk = true;
} catch {
  badItemsOk = false;
}
ok("a non-numeric quantity does not crash the trigger", badItemsOk);

// ── the cancel sweep exists and is not callable by a customer ─────────────
const fn = await sql(
  `select p.proname, p.proconfig, has_function_privilege('authenticated', p.oid, 'execute') as auth_exec
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname in ('cancel_stale_cod_orders','enforce_cod_order_limits')
    order by p.proname`
);
ok("both functions exist", fn.rows.length === 2, JSON.stringify(fn.rows));
ok("cancel_stale_cod_orders has a pinned search_path", fn.rows.every((r) => (r.proconfig || []).some((c) => c.startsWith("search_path="))));
ok("a signed-in customer cannot call the sweep", fn.rows.every((r) => r.auth_exec === false));

const trigger = await sql(
  `select tgname from pg_trigger t join pg_class c on c.oid = t.tgrelid
    where c.relname = 'orders' and not t.tgisinternal`
);
ok("the BEFORE INSERT trigger is installed", trigger.rows.some((r) => r.tgname === "trg_enforce_cod_order_limits"));

// cancel_stale_cod_orders(48) must refuse to be called by a customer even if
// the grant were wrong, because the function itself is SECURITY DEFINER with
// execute revoked. That is what the check above proves.

await db.close();

console.log(`\n${failed === 0 ? "PASS" : "FAIL"} — ${passed} passed, ${failed} failed (real Postgres, PGlite)`);
process.exit(failed === 0 ? 0 : 1);
